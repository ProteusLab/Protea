# gem5/Target/RISC_V/decoder_emitter.py
# C++ decoder module emission (Opcode enum + decodeInstr dispatch).

from typing import Dict, List, Tuple

from lira.arch import Snippet
from lira.arch_utils import ArchIndex

from Generic.instruction import Instruction
from Generic.builders import ConstraintBuilder
from Generic.nodes import render_nodes


def _constraint_fn(index: ArchIndex, snippet: Snippet) -> str:
    nodes = ConstraintBuilder(index).build(snippet.seq)
    body = render_nodes(nodes)
    return f"""\
static uint32_t {snippet.name}(uint32_t machInst)
{{
{body}
}}"""


def gen_protea_decoder(
    index: ArchIndex, insts: List[Instruction], snippets: Dict[str, Snippet]
) -> Tuple[str, str]:
    enum_code = ""
    for inst in insts:
        enum_code += f"    k{inst.name} = {inst.inst_id},\n"
    enum_code += f"    kUnknown = {len(insts)},\n"
    enum_code = enum_code.rstrip("\n")

    hh = f"""\
// Generated by Protea gen_gem5_isa. Do not edit.

#pragma once

#include <cstdint>

namespace gem5::RiscvISA
{{

enum Opcode : uint32_t
{{
{enum_code}
}};

Opcode decodeInstr(uint32_t machInst);

}} // namespace gem5::RiscvISA
"""

    constraint_code = ""
    checks_code = ""
    for inst in insts:
        snip_name = inst.constraint_decode
        constraint_code += _constraint_fn(index, snippets[snip_name]) + "\n"
        checks_code += f"    if ({snip_name}(machInst)) return Opcode::k{inst.name};\n"
    constraint_code = constraint_code.rstrip("\n")
    checks_code = checks_code.rstrip("\n")

    cc = f"""\
// Generated by Protea gen_gem5_isa. Do not edit.

#include "arch/riscv/insts/protea_decoder.hh"
#include "arch/riscv/insts/protea_base_ops.hh"

namespace gem5::RiscvISA
{{

using namespace gem5::RiscvISAInst;

{constraint_code}

Opcode decodeInstr(uint32_t machInst)
{{
{checks_code}
    return Opcode::kUnknown;
}}

}} // namespace gem5::RiscvISA
"""
    return hh, cc
