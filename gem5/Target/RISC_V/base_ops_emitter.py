# gem5/Target/RISC_V/base_ops_emitter.py

from typing import List, Tuple

from lira.arch import Operation
from lira.ir_ops import Asr, Lsl, Lsr

import Generic.base_ops  # noqa: F401  # applies the CppOps mixins

from Generic.types import OperandType


def _lsl_body(self) -> str:
    return f"""b &= {OperandType.bits(self.inputs[0]) - 1};
return a << b;"""


def _lsr_body(self) -> str:
    return f"""b &= {OperandType.bits(self.inputs[0]) - 1};
return a >> b;"""


def _asr_body(self) -> str:
    t = OperandType.gen(self.inputs[0])
    ts = OperandType.gen(self.inputs[0], signed=True)
    return f"""b &= {OperandType.bits(self.inputs[0]) - 1};
return ({t})(({ts})a >> b);"""


Lsl.cpp_body = _lsl_body
Lsr.cpp_body = _lsr_body
Asr.cpp_body = _asr_body


def gen_protea_base_ops(operations: List[Operation]) -> Tuple[str, str]:
    decl_code = ""
    def_code = ""
    for op in sorted(operations, key=lambda o: o.name):
        ret = op.cpp_return_type()
        name = op.name
        params = op.cpp_params()
        decl_code += f"{ret} {name}({params});\n"
        body = op.cpp_body()
        def_code += f"""
{ret} {name}({params})
{{
{body}
}}
"""
    decl_code = decl_code.rstrip("\n")
    def_code = def_code.rstrip("\n")

    hh = f"""\
// Generated by Protea gen_gem5_isa. Do not edit.

#pragma once

#include <cstdint>

#ifdef __SIZEOF_INT128__
typedef unsigned __int128 uint128_t;
typedef __int128 int128_t;
#endif

namespace gem5::RiscvISAInst
{{

{decl_code}

}} // namespace gem5::RiscvISAInst
"""
    cc = f"""\
// Generated by Protea gen_gem5_isa. Do not edit.

#include "arch/riscv/insts/protea_base_ops.hh"

namespace gem5::RiscvISAInst
{{

{def_code}

}} // namespace gem5::RiscvISAInst
"""
    return hh, cc
